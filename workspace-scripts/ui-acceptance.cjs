function monitor(page, name) {
  openPages.push([page,name])
  page.setDefaultTimeout(12000)
  page.on('pageerror', e => errors.push({page:name, error:e.message}))
  page.on('console', m => { if(m.type()==='error' && !m.text().startsWith('Failed to load resource:')) errors.push({page:name,error:m.text()}) })
  page.on('requestfailed', r => {
    const failure=r.failure()?.errorText
    const expectedNavigationReadAbort=navigatingPages.has(page) && r.method()==='GET' && new URL(r.url()).pathname==='/qicai/mobile/notices/summary' && failure==='net::ERR_ABORTED'
    responses.push({page:name,url:r.url(),method:r.method(),failure,expectedCause:injectedFailures.get(r)||(expectedNavigationReadAbort?'page-navigation-aborted-notice-read':null)})
  })
  page.on('response', r => { const pathname=new URL(r.url()).pathname.replace(/^\/prod-api/,''); if(/^\/qicai\/(mobile|admin)\//.test(pathname))endpoints.push({method:r.request().method(),path:pathname,status:r.status()}); if(r.status()>=400) responses.push({page:name,url:r.url(),status:r.status(),expectedCause:deletedCourier&&name==='courier'&&r.request().method()==='GET'&&r.status()===401?({'/qicai/mobile/courier/tasks':'deleted-courier-session','/qicai/mobile/courier/availability':'deleted-courier-availability-session','/qicai/mobile/notices/summary':'deleted-courier-notice-session'}[pathname]||null):null}) })
  page.on('framenavigated', f => { if(f===page.mainFrame()) { const u=new URL(f.url()); visited.add(name + ':' + (u.hash.split('?')[0] || u.pathname)) } })
}
const tap = async (page, text) => {
  await page.getByText(text,{exact:true}).first().waitFor()
  const button = page.locator('uni-button').filter({hasText:new RegExp('^'+text+'$')})
  if(await button.count()) return button.click()
  return page.getByText(text,{exact:true}).click()
}
