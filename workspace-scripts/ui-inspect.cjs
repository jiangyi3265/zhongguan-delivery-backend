const { chromium } = require('C:/Users/jiangyi/AppData/Roaming/npm/node_modules/playwright')
;(async () => {
  const browser = await chromium.launch({ headless: true, args: ['--no-proxy-server'] })
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
  page.on('pageerror', e => console.log('PAGEERROR ' + e.message))
  page.on('console', m => { if (['error', 'warning'].includes(m.type())) console.log('CONSOLE ' + m.text()) })
  page.on('requestfailed', r => console.log('FAILED ' + r.url() + ' ' + r.failure()?.errorText))
  await page.goto(process.argv[2] || 'http://127.0.0.1:5185/', { waitUntil: 'networkidle', timeout: 30000 })
  console.log('URL ' + page.url())
  console.log('BODY ' + await page.locator('body').innerText())
  console.log('INPUTS ' + await page.locator('input,textarea,uni-input').evaluateAll(es=>es.map(e=>e.outerHTML).join('\n')))
  console.log('HTML ' + (await page.content()).slice(-1800))
  await page.screenshot({ path: 'tmp/verification-20260926/inspect.png', fullPage: true })
  await browser.close()
})().catch(e => { console.error(e); process.exitCode = 1 })
